"use client";
import { useState, useCallback } from "react";
import { ToolSchema, BreadcrumbSchema } from "@/app/components/JsonLd";
import SeoContent from "./SeoContent";
import { useTranslation } from "@/lib/i18n/useTranslation";

type CrawlPolicy = "allow" | "block" | "custom";

interface FormData {
  sitemapUrl: string;
  crawlPolicy: CrawlPolicy;
  blockedPaths: string;
  crawlDelay: string;
  blockAiBots: boolean;
  blockImages: boolean;
  customAgents: string;
}

const AI_BOTS = [
  "GPTBot", "ChatGPT-User", "Google-Extended", "CCBot", "anthropic-ai",
  "ClaudeBot", "Bytespider", "FacebookBot", "Applebot-Extended",
  "PerplexityBot", "Cohere-ai", "Amazonbot", "meta-externalagent",
];

function generateRobotsTxt(form: FormData): string {
  const lines: string[] = [];
  lines.push(`# Robots.txt generated by ToolCraftKit.com`);
  lines.push(`# ${new Date().toISOString().split("T")[0]}`);
  lines.push(``);

  if (form.blockAiBots) {
    lines.push(`# Block AI crawlers and training bots`);
    for (const bot of AI_BOTS) {
      lines.push(`User-agent: ${bot}`);
      lines.push(`Disallow: /`);
      lines.push(``);
    }
  }

  if (form.customAgents.trim()) {
    const agents = form.customAgents.split("\n").map(a => a.trim()).filter(Boolean);
    for (const agent of agents) {
      lines.push(`User-agent: ${agent}`);
      lines.push(`Disallow: /`);
      lines.push(``);
    }
  }

  lines.push(`User-agent: *`);

  if (form.crawlPolicy === "allow") {
    lines.push(`Allow: /`);
  } else if (form.crawlPolicy === "block") {
    lines.push(`Disallow: /`);
  } else {
    lines.push(`Allow: /`);
    if (form.blockedPaths.trim()) {
      const paths = form.blockedPaths.split("\n").map(p => p.trim()).filter(Boolean);
      for (const path of paths) {
        const normalized = path.startsWith("/") ? path : `/${path}`;
        lines.push(`Disallow: ${normalized}`);
      }
    }
  }

  if (form.crawlDelay && form.crawlDelay !== "0") {
    lines.push(`Crawl-delay: ${form.crawlDelay}`);
  }

  if (form.blockImages) {
    lines.push(``);
    lines.push(`User-agent: *`);
    lines.push(`Disallow: /*.jpg$`);
    lines.push(`Disallow: /*.jpeg$`);
    lines.push(`Disallow: /*.png$`);
    lines.push(`Disallow: /*.gif$`);
    lines.push(`Disallow: /*.webp$`);
    lines.push(`Disallow: /*.svg$`);
  }

  lines.push(``);
  if (form.sitemapUrl.trim()) {
    lines.push(`Sitemap: ${form.sitemapUrl}`);
  }

  return lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd();
}

const s = {
  page: { maxWidth: 760, margin: "0 auto", padding: "32px 20px 0" } as const,
  h1: { fontSize: 28, fontWeight: 700 as const, color: "#1C1917", marginBottom: 4, marginTop: 0 },
  sub: { fontSize: 14, color: "#78716C", marginBottom: 24, marginTop: 8 },
  card: { background: "#fff", border: "1px solid #E7E5E4", borderRadius: 10, padding: 20, marginBottom: 16 } as const,
  cardTitle: { fontSize: 16, fontWeight: 600 as const, color: "#1C1917", marginBottom: 16, marginTop: 0 },
  label: { fontSize: 13, fontWeight: 600 as const, color: "#1C1917", marginBottom: 6, display: "block" as const },
  input: { width: "100%", border: "1px solid #E7E5E4", borderRadius: 8, padding: "10px 12px", fontSize: 14, outline: "none", boxSizing: "border-box" as const, marginBottom: 12, color: "#1C1917", background: "#fff" },
  select: { width: "100%", border: "1px solid #E7E5E4", borderRadius: 8, padding: "10px 12px", fontSize: 14, outline: "none", boxSizing: "border-box" as const, marginBottom: 12, color: "#1C1917", background: "#fff", cursor: "pointer" as const },
  textarea: { width: "100%", minHeight: 100, border: "1px solid #E7E5E4", borderRadius: 8, padding: "10px 12px", fontSize: 14, lineHeight: 1.6, color: "#1C1917", background: "#fff", resize: "vertical" as const, outline: "none", boxSizing: "border-box" as const, marginBottom: 12, fontFamily: "inherit" },
  checkRow: { display: "flex" as const, alignItems: "center" as const, gap: 10, marginBottom: 10, cursor: "pointer" as const },
  checkLabel: { fontSize: 14, color: "#1C1917", cursor: "pointer" as const, userSelect: "none" as const },
  btn: { background: "#0D9488", color: "#fff", border: "none", borderRadius: 8, padding: "12px 24px", fontSize: 15, fontWeight: 600 as const, cursor: "pointer" as const, width: "100%" },
  btnSecondary: { background: "#F5F5F4", color: "#1C1917", border: "1px solid #E7E5E4", borderRadius: 8, padding: "10px 20px", fontSize: 14, fontWeight: 600 as const, cursor: "pointer" as const },
  output: { background: "#FAFAF9", border: "1px solid #E7E5E4", borderRadius: 10, padding: 20, marginBottom: 16 },
  outputTextarea: { width: "100%", minHeight: 300, border: "1px solid #E7E5E4", borderRadius: 8, padding: 16, fontSize: 13, lineHeight: 1.7, color: "#1C1917", fontFamily: "'Courier New', monospace", background: "#fff", resize: "vertical" as const, outline: "none", boxSizing: "border-box" as const },
  grid2: { display: "grid" as const, gridTemplateColumns: "1fr 1fr", gap: 12 },
};

export default function ClientPage() {
  const { t } = useTranslation();
  const [form, setForm] = useState<FormData>({
    sitemapUrl: "",
    crawlPolicy: "custom",
    blockedPaths: "/admin/\n/private/\n/api/\n/tmp/",
    crawlDelay: "0",
    blockAiBots: false,
    blockImages: false,
    customAgents: "",
  });
  const [output, setOutput] = useState("");
  const [copied, setCopied] = useState(false);

  const handleGenerate = useCallback(() => { setOutput(generateRobotsTxt(form)); setCopied(false); }, [form]);
  const handleCopy = useCallback(async () => {
    if (!output) return;
    try { await navigator.clipboard.writeText(output); setCopied(true); setTimeout(() => setCopied(false), 2000); } catch {}
  }, [output]);
  const handleDownload = useCallback(() => {
    if (!output) return;
    const blob = new Blob([output], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url; a.download = "robots.txt"; a.click();
    URL.revokeObjectURL(url);
  }, [output]);

  const setField = <K extends keyof FormData>(key: K, value: FormData[K]) => setForm(p => ({ ...p, [key]: value }));

  return (
    <div style={s.page}>
      <ToolSchema name="Robots.txt Generator" description="Generate a robots.txt file for your website to control search engine crawling." slug="robots-txt-generator" category="WebApplication" />
      <BreadcrumbSchema items={[{ name: "Home", url: "https://toolcraftkit.com" }, { name: "Tools", url: "https://toolcraftkit.com/tools" }, { name: "Robots.txt Generator", url: "https://toolcraftkit.com/tools/robots-txt-generator" }]} />

      <h1 style={s.h1}>"Robots.txt Generator"</h1>
      <p style={s.sub}>"Generate a robots.txt file to control how search engines crawl your website."</p>

      <div style={s.card}>
        <h2 style={s.cardTitle}>Configuration</h2>
        <label style={s.label}>Sitemap URL</label>
        <input style={s.input} placeholder="https://example.com/sitemap.xml" value={form.sitemapUrl} onChange={e => setField("sitemapUrl", e.target.value)} />
        <label style={s.label}>Default Crawl Behavior</label>
        <select style={s.select} value={form.crawlPolicy} onChange={e => setField("crawlPolicy", e.target.value as CrawlPolicy)}>
          <option value="allow">Allow all crawling</option>
          <option value="block">Block all crawling</option>
          <option value="custom">Custom (allow with exceptions)</option>
        </select>
        {form.crawlPolicy === "custom" && (
          <>
            <label style={s.label}>Paths to Block (one per line)</label>
            <textarea style={s.textarea} value={form.blockedPaths} onChange={e => setField("blockedPaths", e.target.value)} placeholder="/admin/&#10;/private/&#10;/api/" />
          </>
        )}
        <div style={s.grid2}>
          <div>
            <label style={s.label}>Crawl Delay (seconds)</label>
            <select style={s.select} value={form.crawlDelay} onChange={e => setField("crawlDelay", e.target.value)}>
              <option value="0">None</option>
              <option value="1">1 second</option>
              <option value="5">5 seconds</option>
              <option value="10">10 seconds</option>
              <option value="30">30 seconds</option>
            </select>
          </div>
          <div style={{ display: "flex", flexDirection: "column" as const, justifyContent: "center" }}>
            <label style={s.checkRow} onClick={() => setField("blockAiBots", !form.blockAiBots)}>
              <input type="checkbox" checked={form.blockAiBots} readOnly style={{ accentColor: "#0D9488" }} />
              <span style={s.checkLabel}>Block AI training bots</span>
            </label>
            <label style={s.checkRow} onClick={() => setField("blockImages", !form.blockImages)}>
              <input type="checkbox" checked={form.blockImages} readOnly style={{ accentColor: "#0D9488" }} />
              <span style={s.checkLabel}>Block image crawling</span>
            </label>
          </div>
        </div>
        <label style={s.label}>Block Specific User Agents (one per line, optional)</label>
        <textarea style={{ ...s.textarea, minHeight: 60 }} value={form.customAgents} onChange={e => setField("customAgents", e.target.value)} placeholder="SemrushBot&#10;AhrefsBot" />
        <button style={s.btn} onClick={handleGenerate}>Generate robots.txt</button>
      </div>

      {output && (
        <div style={s.output}>
          <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", marginBottom: 12 }}>
            <h2 style={{ ...s.cardTitle, marginBottom: 0 }}>Your robots.txt</h2>
            <div style={{ display: "flex", gap: 8 }}>
              <button style={s.btnSecondary} onClick={handleCopy}>{copied ? "✓ Copied!" : "Copy"}</button>
              <button style={s.btnSecondary} onClick={handleDownload}>Download</button>
            </div>
          </div>
          <textarea style={s.outputTextarea} value={output} readOnly />
        </div>
      )}

      <SeoContent />
    </div>
  );
}
